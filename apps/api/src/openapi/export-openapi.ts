// Writes packages/contracts/openapi.yaml from the running route table (NFR-MNT-04).
// CI runs this and fails when the committed file differs: `git diff --exit-code`.
// Usage: pnpm --filter @belle/api openapi:export (runs from the tsc build, which emits the
// decorator metadata Nest DI needs; tsx/esbuild does not).
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// The export never queries the database; a placeholder URL satisfies env validation.
// Set before AppModule is imported, because ConfigModule validates at import time.
process.env['DATABASE_URL'] ??=
  'postgresql://openapi:openapi@localhost:5432/openapi';
process.env['LOG_LEVEL'] = 'silent';

const { NestFactory } = await import('@nestjs/core');
const { stringify } = await import('yaml');
const { AppModule } = await import('../app.module.js');
const { buildOpenApiDocument, configureApp } =
  await import('../bootstrap/configure-app.js');

const here = dirname(fileURLToPath(import.meta.url));
const target = resolve(here, '../../../../packages/contracts/openapi.yaml');

const app = await NestFactory.create(AppModule, { logger: false });
configureApp(app);
const document = buildOpenApiDocument(app);
writeFileSync(
  target,
  '# Generated by apps/api (pnpm --filter @belle/api openapi:export). Do not edit by hand.\n' +
    // No YAML anchors/aliases: Swagger reuses objects, and stable sorted output keeps diffs readable.
    stringify(document, {
      sortMapEntries: true,
      lineWidth: 0,
      aliasDuplicateObjects: false,
    }),
);
await app.close();
console.log(`OpenAPI written to ${target}`);
