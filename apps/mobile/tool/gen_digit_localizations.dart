// Writes lib/app/l10n/gen/digit_localizations.dart from the generated
// AppLocalizations. A message that takes a number, or a time or date handed
// in as text ([digitArguments]), is written with the customer's digits
// (FR-LOC-02), separators included. When it also holds an identifier
// ([identifierArguments]), only the time or date arguments are converted, so
// "BB-1002" stays as it is. Messages without numbers are passed through:
// "2D" in a label stays Western.
//
// Run after `flutter gen-l10n`:
//   dart run tool/gen_digit_localizations.dart
// test/app/digit_localizations_test.dart fails when the file is stale.
import 'dart:io';

const source = 'lib/app/l10n/gen/app_localizations.dart';
const target = 'lib/app/l10n/gen/digit_localizations.dart';

/// Text arguments that carry times, dates or counts already formatted.
const digitArguments = {
  'time',
  'open',
  'close',
  'start',
  'end',
  'when',
  'date',
  'left',
  'eta',
  'stems',
  'count',
};

/// Text arguments that must keep their Western digits.
const identifierArguments = {'number', 'code', 'link', 'version', 'phone'};

final _member = RegExp(
  r'^  String (?:get (\w+)|(\w+)\(([^)]*)\));',
  multiLine: true,
);
final _numeric = RegExp(r'\b(int|num|double)\b');

/// The Dart source of the wrapper for this AppLocalizations source.
String digitLocalizationsSource(String abstractClass) {
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_digit_localizations.dart. Do not edit.')
    ..writeln('// ignore_for_file: type=lint')
    ..writeln()
    ..writeln(
      "import 'package:belle_biens/app/l10n/gen/app_localizations.dart';",
    )
    ..writeln("import 'package:belle_biens/core/text/digits.dart';")
    ..writeln()
    ..writeln('/// [AppLocalizations] with the numbers inside messages in the')
    ..writeln("/// customer's digits.")
    ..writeln('class DigitLocalizations extends AppLocalizations {')
    ..writeln('  DigitLocalizations(this._base, this._numerals)')
    ..writeln('      : super(_base.localeName);')
    ..writeln()
    ..writeln('  final AppLocalizations _base;')
    ..writeln('  final Numerals _numerals;')
    ..writeln()
    ..writeln('  String _d(String text) => localizeDigits(text, _numerals);');
  for (final m in _member.allMatches(abstractClass)) {
    final getter = m.group(1);
    if (getter != null) {
      out
        ..writeln()
        ..writeln('  @override')
        ..writeln('  String get $getter => _base.$getter;');
      continue;
    }
    final name = m.group(2)!;
    final params = m
        .group(3)!
        .split(',')
        .map((p) => p.trim())
        .where((p) => p.isNotEmpty)
        .toList();
    String argOf(String p) => p.split(RegExp(r'\s+')).last;
    final names = params.map(argOf).toList();
    final hasIdentifier = names.any(identifierArguments.contains);
    final whole =
        !hasIdentifier &&
        (params.any(_numeric.hasMatch) || names.any(digitArguments.contains));
    final args = params
        .map((p) {
          final arg = argOf(p);
          final text = !_numeric.hasMatch(p) && digitArguments.contains(arg);
          return text && !whole ? '_d($arg)' : arg;
        })
        .join(', ');
    final call = '_base.$name($args)';
    out
      ..writeln()
      ..writeln('  @override')
      ..writeln(
        '  String $name(${params.join(', ')}) => '
        '${whole ? '_d($call)' : call};',
      );
  }
  out.writeln('}');
  return out.toString();
}

void main() {
  File(target).writeAsStringSync(
    digitLocalizationsSource(File(source).readAsStringSync()),
  );
  final format = Process.runSync('dart', ['format', target], runInShell: true);
  stdout.write(format.stdout);
}
