// Generates layouts/bouquet-slots.v1.json: where flowers, greens, wrap, ribbon and
// extras sit on the 2D preview canvas, for each bouquet size (FR-D2D-02/03).
// Run once when the layout changes: node scripts/generate-layouts.mjs
//
// The output is data: the API and the app read it and never recompute the spiral,
// so both place every stem at the same integer position (NFR-MNT-03).
// Canvas: 1000 x 1250 units (4:5). Positions, sizes and angles are integers.

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const GOLDEN_ANGLE = 137.50776405003785; // degrees
const CENTER = { x: 500, y: 470 };

/** Bouquet head radius, flower size, slot counts per size. */
const SIZES = {
  small: { radius: 210, flower: 112, flowers: 14, greens: 6 },
  medium: { radius: 290, flower: 92, flowers: 30, greens: 10 },
  large: { radius: 340, flower: 74, flowers: 50, greens: 14 },
  luxury: { radius: 380, flower: 62, flowers: 60, greens: 18 },
};

function flowerSlots({ radius, flower, flowers }) {
  const slots = [];
  for (let i = 0; i < flowers; i++) {
    const t = (i + 0.5) / flowers;
    const r = radius * Math.sqrt(t);
    const a = (i * GOLDEN_ANGLE * Math.PI) / 180;
    slots.push({
      x: Math.round(CENTER.x + r * Math.cos(a)),
      // A slightly flattened dome reads as a bouquet seen from the front.
      y: Math.round(CENTER.y + r * Math.sin(a) * 0.82),
      size: Math.round(flower * (1.1 - 0.18 * Math.sqrt(t))),
      rotation: ((i * 47) % 360) - 180,
    });
  }
  return slots;
}

function greenSlots({ radius, flower, greens }) {
  const slots = [];
  for (let j = 0; j < greens; j++) {
    // Evenly around the head, starting at the top, leaning outwards.
    const deg = -90 + (360 * j) / greens;
    const a = (deg * Math.PI) / 180;
    const r = radius * 1.02;
    slots.push({
      x: Math.round(CENTER.x + r * Math.cos(a)),
      y: Math.round(CENTER.y + r * Math.sin(a) * 0.82),
      size: Math.round(flower * 1.25),
      rotation: Math.round(deg + 90),
    });
  }
  return slots;
}

function layout(name, cfg) {
  return {
    size: name,
    flowers: flowerSlots(cfg),
    greens: greenSlots(cfg),
    wrapBack: { x: 500, y: 760, size: Math.round(cfg.radius * 2.3), rotation: 0 },
    wrapFront: { x: 500, y: 930, size: Math.round(cfg.radius * 1.9), rotation: 0 },
    ribbon: { x: 500, y: 960, size: 150, rotation: 0 },
    extras: [
      { x: 215, y: 1060, size: 170, rotation: -8 },
      { x: 785, y: 1060, size: 170, rotation: 8 },
      { x: 150, y: 830, size: 140, rotation: -12 },
      { x: 850, y: 830, size: 140, rotation: 12 },
    ],
  };
}

const out = {
  version: 1,
  description:
    'Slot layouts for the 2D bouquet preview (FR-D2D-02/03). Canvas 1000 x 1250 (4:5); all numbers are integers. Flower slots go from the centre outwards (golden-angle spiral). Generated by scripts/generate-layouts.mjs; the layout algorithm is in vectors/layout.json.',
  canvas: { width: 1000, height: 1250 },
  layouts: Object.fromEntries(Object.entries(SIZES).map(([k, v]) => [k, layout(k, v)])),
};

writeFileSync(join(root, 'layouts/bouquet-slots.v1.json'), JSON.stringify(out, null, 2) + '\n');
console.log('wrote layouts/bouquet-slots.v1.json');
